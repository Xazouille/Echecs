// Pour une suite de coups SAN, renvoie le nombre de demi-coups « théoriques »
// et le nom de l'ouverture la plus précise rencontrée.
export function bookInfo(sans) {
  let depth = 0;
  let name = '';
  let nameLen = 0;
  for (const line of LINES) {
    let k = 0;
    while (k < line.moves.length && k < sans.length && line.moves[k] === sans[k]) k++;
    if (k > depth) depth = k;
    if (k === line.moves.length && k >= nameLen) {
      nameLen = k;
      name = line.name;
    } else if (k > nameLen && k >= 2) {
      nameLen = k;
      name = line.name;
    }
  }
  return { depth, name };
}

// Nom lisible à partir de l'URL d'ouverture fournie par Chess.com (champ ECOUrl).
export function nameFromEcoUrl(url) {
  if (!url) return '';
  const slug = url.split('/openings/')[1];
  if (!slug) return '';
  return decodeURIComponent(slug)
    .replace(/-\d.*$/, '')
    .replace(/-/g, ' ')
    .trim();
}
